type LanguageContextValue = {
  language: AppLanguage;
  isRTL: boolean;
  toggleLanguage: () => void;
  t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<AppLanguage>('en');

  useEffect(() => {
    let active = true;
    void AsyncStorage.getItem(languageStorageKey).then((savedLanguage) => {
      if (active && (savedLanguage === 'en' || savedLanguage === 'ur')) setLanguage(savedLanguage);
    }).catch((error: unknown) => {
      console.error('Unable to load saved language:', error);
    });
    return () => { active = false; };
  }, []);

  useEffect(() => {
    if (typeof document === 'undefined') return;
    const direction = language === 'ur' ? 'rtl' : 'ltr';
    document.documentElement.dir = direction;
    document.body.dir = direction;
  }, [language]);

  const toggleLanguage = useCallback(() => {
    const next = language === 'en' ? 'ur' : 'en';
    setLanguage(next);
    void AsyncStorage.setItem(languageStorageKey, next).catch((error: unknown) => {
      console.error('Unable to save selected language:', error);
    });
  }, [language]);

  const value = useMemo(() => ({
    language,
    isRTL: language === 'ur',
    toggleLanguage,
    t: (text: string) => language === 'ur' ? urduTranslations[text] ?? text : text,
  }), [language, toggleLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}
